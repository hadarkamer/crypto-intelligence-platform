"""Loopback-only QA routes for the signed-in fixture worksheet. Never run a collector worker."""
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
import json
import os
from pathlib import Path
import threading
from unittest.mock import patch
from uuid import UUID, uuid4

from aiohttp import web

import operator_desktop
import operator_login
import operator_window
from prepare import PAGE, PINS, build
import tempfile

INCIDENT = '12d98060-4937-4e7f-8448-bddad76df2e5'


class Waiting:
    def __init__(self):
        self.lock = threading.Lock()
        self.active = None
        self.releases = 0
        self.cleanup_failed = False

    @contextmanager
    def connect(self):
        # The only store served by this runner is the disposable incident below.
        yield self

    def status(self, _conn, incident_id=None, job_id=None):
        with self.lock:
            if incident_id not in (None, INCIDENT) or job_id:
                return {'status': 'none', 'incident_id': None}
            return {'status': 'in_progress' if self.active else 'waiting', 'incident_id': INCIDENT}

    def reserve(self, incident):
        with self.lock:
            if incident != INCIDENT or self.active or self.cleanup_failed:
                raise operator_login.LoginIncidentError('login_window_unavailable')
            self.active = str(uuid4())
            return self.active, datetime.now(timezone.utc) + timedelta(minutes=10), ('BTC', 1, '12H'), 0

    def release(self, window):
        with self.lock:
            if self.active != window.id:
                raise AssertionError('lease_mismatch')
            if window.desktop and (window.desktop.proc.returncode is None or Path(window.desktop.directory.name).exists()):
                self.cleanup_failed = True
                raise AssertionError('private_browser_or_directory_still_active')
            self.active = None
            self.releases += 1
            print(json.dumps({'fixture_lease_released': self.releases}), flush=True)

    def finish(self, *args):
        raise AssertionError('fixture_cannot_persist_state')


def main():
    # Compare every generated byte with the approved test-only overlay. Running this
    # file with the production desktop or a custom URL is never supported.
    original = Path('/opt/coinglass-window-fixture/originals')
    with tempfile.TemporaryDirectory() as tmp:
        expected = Path(tmp)/'expected'
        build(original, expected)
        for name in PINS:
            if (operator_desktop.HERE/name).read_bytes() != (expected/name).read_bytes():
                raise SystemExit('fixture_overlay_required')
        managed = Path('/etc/chromium/policies/managed/operator.json')
        if json.loads(managed.read_text()) != json.loads((expected/'operator_chromium_policy.json').read_text()):
            raise SystemExit('fixture_policy_required')
    for name in ('DATABASE_URL', 'COINGLASS_SESSION_KEY', 'OPENAI_API_KEY', 'COINGLASS_COOKIE_HEADER', 'STORAGE_STATE_JSON'):
        if name in os.environ:
            raise SystemExit('nonfixture_configuration')
    actor = str(UUID(os.environ['QA_OWNER_UUID']))
    token = os.environ['QA_BRIDGE_TOKEN']
    if len(token) < 40:
        raise SystemExit('fresh_ephemeral_fixture_bridge_required')
    os.environ.update(COINGLASS_OPERATOR_ID=actor, COINGLASS_APP_ORIGIN='https://app.example.org',
        COINGLASS_OPERATOR_ORIGIN='https://collector.example.org', COINGLASS_COLLECTOR_TOKEN=token,
        COINGLASS_OPERATOR_DESKTOP_ENABLED='true', COINGLASS_SESSION_STORE_ENABLED='true')
    store = Waiting()
    captured = []
    real_manager = operator_window.WindowManager

    def capture_manager(*args):
        manager = real_manager(*args)
        captured.append(manager)
        return manager

    @web.middleware
    async def second_viewer_receipt(request, handler):
        response = await handler(request)
        if request.path == operator_window.PREFIX + '/display' and response.status == 403:
            manager = captured[0]
            window = manager.authorized(request)
            if window and window.attached and manager.same_origin(request):
                print('{"authenticated_second_viewer_denied":true}', flush=True)
        return response

    app = web.Application(middlewares=[second_viewer_receipt])
    # Production admission, bridge auth, noVNC assets, runtime probe, framebuffer
    # and watchdog are all genuine. The source incident is the only substituted store.
    with patch.object(operator_window, 'WindowManager', side_effect=capture_manager), \
         patch.object(operator_window, 'Database', return_value=store), \
         patch.object(operator_login, 'incident_status', side_effect=store.status):
        operator_login.register_operator_login(app, store, True)
        web.run_app(app, host='127.0.0.1', port=8765, access_log=None, print=None)


if __name__ == '__main__':
    main()
